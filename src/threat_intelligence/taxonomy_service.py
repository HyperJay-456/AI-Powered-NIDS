class TaxonomyService:
    """Manages dataset attack label taxonomy and threat family categorizations."""

    @staticmethod
    def normalize_label(label: str) -> str:
        """Standardize attack label for case-insensitive and whitespace-tolerant lookups."""
        if not label:
            return ""
        # Strip leading/trailing whitespace, replace consecutive spaces, lowercase
        cleaned = " ".join(str(label).strip().split())
        return cleaned.lower()

    @classmethod
    def get_taxonomy_item(cls, label: str) -> DatasetLabelTaxonomyItem:
        """Retrieve standardized taxonomy item for an original dataset label."""
        orig_str = str(label).strip() if label else "UNKNOWN"
        norm_key = cls.normalize_label(orig_str)

        # Match against known definitions
        matched_item = None
        for known_name, (family, desc) in DEFAULT_TAXONOMY_DESCRIPTIONS.items():
            if cls.normalize_label(known_name) == norm_key:
                label_id = f"tax_{norm_key.replace(' ', '_').replace('-', '_')}"
                return DatasetLabelTaxonomyItem(
                    label_id=label_id,
                    original_label=orig_str,
                    normalized_label=norm_key,
                    display_label=known_name,
                    broad_family=family,
                    description=desc,
                    dataset_source="CIC-IDS-2017",
                    mapping_status="Candidate",
                )

        # Unknown / unclassified label
        return DatasetLabelTaxonomyItem(
            label_id=f"tax_{norm_key.replace(' ', '_')}",
            original_label=orig_str,
            normalized_label=norm_key,
            display_label=orig_str,
            broad_family=AttackFamily.OTHER,
            description="Unclassified traffic class without verified taxonomy definition in project baseline.",
            dataset_source="Custom / Unknown",
            mapping_status="Unmapped",
        )

    @classmethod
    def get_all_taxonomy_items(cls) -> List[DatasetLabelTaxonomyItem]:
        """Retrieve all taxonomy items for the 15 benchmark CIC-IDS-2017 classes."""
        items: List[DatasetLabelTaxonomyItem] = []
        for known_class in settings.dataset.known_attack_classes:
            items.append(cls.get_taxonomy_item(known_class))
        return items
